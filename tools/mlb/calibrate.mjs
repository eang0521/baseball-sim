// Measure how the sim turns ratings into stats, so real stat lines can be converted back into ratings.
//
// Runs many full games in parallel. In each game one club has random hitters facing league-average
// pitching, and the other club's random pitchers face league-average hitting. A weighted quadratic
// regression of per-PA rates on ratings is written to js/data/mlb/calibration.json.
//
//   node tools/mlb/calibrate.mjs [games=2400] [workers=cpus-2]
import { Worker, isMainThread, parentPort, workerData } from 'node:worker_threads';
import { cpus } from 'node:os';
import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { terms } from './model.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(here, '..', '..', 'js', 'data', 'mlb', 'calibration.json');

// Rates we model. Hitters and pitchers share the same outcome set (per PA / per batter faced).
const OUTCOMES = ['k', 'bb', 'hr', 'h1', 'xbh'];
export const HIT_FEATS = ['contact', 'power', 'eye', 'speed'];
export const PIT_FEATS = ['velo', 'control', 'stuff'];

if (isMainThread) {
  const games = +process.argv[2] || 2400;
  const nw = +process.argv[3] || Math.max(1, cpus().length - 2);
  const per = Math.ceil(games / nw);
  const t0 = Date.now();
  let done = 0;
  const hitRows = [], pitRows = [];
  await Promise.all(Array.from({ length: nw }, (_, w) => new Promise((resolve, reject) => {
    const wk = new Worker(fileURLToPath(import.meta.url), { workerData: { seed: 7000 + w * 100003, games: per } });
    wk.on('message', (m) => {
      if (m.progress) {
        done++;
        if (done % 100 === 0) console.log(`${done}/${per * nw} games, ${((Date.now() - t0) / 1000).toFixed(0)}s`);
      } else {
        hitRows.push(...m.hit);
        pitRows.push(...m.pit);
        resolve();
      }
    });
    wk.on('error', reject);
  })));
  console.log(`${hitRows.length} hitter-games, ${pitRows.length} pitcher-games in ${((Date.now() - t0) / 1000).toFixed(0)}s`);

  const hit = fitAll(hitRows, HIT_FEATS);
  const pit = fitAll(pitRows, PIT_FEATS);
  // League-average baseline for the sim: the rates of the average opposition used above.
  const base = (rows) => Object.fromEntries(OUTCOMES.map((o) => [o, rows.reduce((s, r) => s + r[o], 0) / rows.reduce((s, r) => s + r.pa, 0)]));
  const out = {
    note: 'Generated by tools/mlb/calibrate.mjs. Per-PA rate models: rate = sum(coef * term). Terms are 1, x_i, x_i*x_j (i<=j) on (rating-55)/20.',
    games: per * nw,
    hitter: { feats: HIT_FEATS, models: hit },
    pitcher: { feats: PIT_FEATS, models: pit },
    // Rates of the average-opposition side (what a "55 everywhere" club produces / allows).
    simLeague: { vsAvgPitching: base(hitRows), vsAvgHitting: base(pitRows) },
  };
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, JSON.stringify(out, null, 1));
  console.log('wrote', OUT);
  for (const [who, m, feats] of [['hitter', hit, HIT_FEATS], ['pitcher', pit, PIT_FEATS]]) {
    console.log(`\n${who}`);
    for (const o of OUTCOMES) {
      const lo = predict(m[o], feats.map(() => 35)), mid = predict(m[o], feats.map(() => 55)), hi = predict(m[o], feats.map(() => 75));
      const sens = feats.map((f, i) => {
        const x = feats.map(() => 55); x[i] = 75;
        return `${f}+20:${((predict(m[o], x) - mid) * 100).toFixed(2)}`;
      }).join(' ');
      console.log(`  ${o.padEnd(4)} all35 ${(lo * 100).toFixed(2)}%  all55 ${(mid * 100).toFixed(2)}%  all75 ${(hi * 100).toFixed(2)}%  r2=${m[o].r2.toFixed(3)}  ${sens}`);
    }
  }
} else {
  await runWorker(workerData);
}

// ---------- regression ----------
export function predict(model, x) {
  const t = terms(x);
  let s = 0;
  for (let i = 0; i < t.length; i++) s += model.coef[i] * t[i];
  return Math.max(0, s);
}

function fitAll(rows, feats) {
  const out = {};
  for (const o of OUTCOMES) out[o] = fit(rows, feats, o);
  return out;
}

// Weighted least squares on per-PA rates (weight = PA), solved with the normal equations.
function fit(rows, feats, o) {
  const n = terms(feats.map(() => 55)).length;
  const A = Array.from({ length: n }, () => new Float64Array(n));
  const b = new Float64Array(n);
  let sw = 0, swy = 0, swyy = 0;
  for (const r of rows) {
    if (!r.pa) continue;
    const t = terms(feats.map((f) => r[f]));
    const y = r[o] / r.pa, w = r.pa;
    for (let i = 0; i < n; i++) {
      b[i] += w * t[i] * y;
      for (let j = 0; j < n; j++) A[i][j] += w * t[i] * t[j];
    }
    sw += w; swy += w * y; swyy += w * y * y;
  }
  const coef = solve(A, b);
  // r2 against per-PA Bernoulli noise is naturally small; it's here only as a sanity check.
  let sse = 0;
  for (const r of rows) {
    if (!r.pa) continue;
    const y = r[o] / r.pa;
    let p = 0; const t = terms(feats.map((f) => r[f]));
    for (let i = 0; i < n; i++) p += coef[i] * t[i];
    sse += r.pa * (y - p) ** 2;
  }
  const sst = swyy - swy * swy / sw;
  return { coef: [...coef].map((c) => +c.toFixed(6)), r2: 1 - sse / sst };
}

function solve(A, b) {
  const n = b.length;
  const M = A.map((row, i) => [...row, b[i]]);
  for (let c = 0; c < n; c++) {
    let p = c;
    for (let r = c + 1; r < n; r++) if (Math.abs(M[r][c]) > Math.abs(M[p][c])) p = r;
    [M[c], M[p]] = [M[p], M[c]];
    for (let r = 0; r < n; r++) {
      if (r === c) continue;
      const f = M[r][c] / M[c][c];
      for (let k = c; k <= n; k++) M[r][k] -= f * M[c][k];
    }
  }
  return M.map((row, i) => row[n] / row[i]);
}

// ---------- worker ----------
async function runWorker({ seed, games }) {
  const { Game } = await import('../../js/sim/game.js');
  const { randomTeam, FIELD_POS } = await import('../../js/data/teams.js');
  const { RNG } = await import('../../js/sim/rng.js');
  const rng = new RNG(seed);
  const U = (a, b) => Math.round(rng.range(a, b));
  const REPS = [['FF', 'SL', 'CH'], ['FF', 'CU', 'CH'], ['SI', 'SL', 'CH'], ['FF', 'SL', 'CU', 'CH'],
    ['FF', 'FC', 'CU'], ['SI', 'FC', 'SL'], ['FF', 'FS', 'SL'], ['FF', 'SL'], ['SI', 'CH', 'CU']];
  const hit = [], pit = [];
  for (let g = 0; g < games; g++) {
    const avgA = randomTeam(seed + g * 2 + 1, { id: 'a', quality: 55 });
    const avgB = randomTeam(seed + g * 2 + 2, { id: 'b', quality: 55 });
    // Club X: random hitters, average pitchers.
    const X = { ...avgA, id: 'x', lineup: avgA.lineup.map((h) => ({ ...h, contact: U(22, 95), power: U(22, 95), eye: U(22, 95), speed: U(22, 95) })) };
    // Club Y: average hitters, random pitchers.
    const Y = {
      ...avgB, id: 'y', pitchers: avgB.pitchers.map((p) => {
        const stuff = U(25, 92);
        const rep = rng.pick(REPS);
        return {
          ...p, velo: U(89, 99), control: U(22, 95),
          pitches: rep.map((t, i) => ({ type: t, rating: Math.max(1, Math.min(99, Math.round(stuff + rng.gauss(i === 0 ? 2 : 0, 5)))) })),
        };
      }),
    };
    const swap = rng.chance(0.5);
    const game = new Game(swap ? Y : X, swap ? X : Y, { seed: seed * 31 + g });
    game.simToEnd();
    const sx = game.sides[swap ? 1 : 0], sy = game.sides[swap ? 0 : 1];
    for (const h of X.lineup) {
      const b = sx.bat.get(h.id);
      hit.push({ contact: h.contact, power: h.power, eye: h.eye, speed: h.speed, ...outcomes(b) });
    }
    for (const p of Y.pitchers) {
      const s = sy.pit.get(p.id);
      if (!s || !s.bf) continue;
      const stuff = p.pitches.reduce((a, q) => a + q.rating, 0) / p.pitches.length;
      pit.push({ velo: 55 + (p.velo - 94) * 4, control: p.control, stuff, ...pitOutcomes(s) });
    }
    parentPort.postMessage({ progress: 1 });
  }
  parentPort.postMessage({ hit, pit });
}

function outcomes(b) {
  return { pa: b.pa, k: b.so, bb: b.bb + b.hbp, hr: b.hr, h1: b.h - b.hr - b.d - b.t, xbh: b.d + b.t };
}

function pitOutcomes(s) {
  return { pa: s.bf, k: s.so, bb: s.bb + s.hbp, hr: s.hr, h1: s.h - s.hr - s.d - s.t, xbh: s.d + s.t };
}
